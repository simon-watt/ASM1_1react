MatrixXd jacobian(VectorXd y,double tau,double R,double KLA,double w)
{
	MatrixXd J(12,12);

	double SI=y(0),SS=y(1),XI=y(2),XS=y(3),XBH=y(4),XBA=y(5);
	double XP=y(6),SO=y(7),SNO=y(8),SNH=y(9),SND=y(10),XND=y(11);
/*
 	double KS=20,KOA=0.4,KOH=0.2,KNO=0.5,KNH=1,KX=0.03,KA=0.08,KH=3;
	double muh=6,mua=0.8,YH=0.67,YA=0.24,etag=0.8,etah=0.4,fp=0.08;
	double bh=0.22,ba=0.05,ixb=0.086,ixp=0.06,SO_max=10;

	double SI_in=2,SS_in=200,XI_in=3,XS_in=100,XBH_in=0,XBA_in=0;
	double XP_in=0,SO_in=2,SNO_in=1,SNH_in=15,SND_in=15,XND_in=9;
*/

	double KS=param.KS,KOA=param.KOA,KOH=param.KOH,KNO=param.KNO,KNH=param.KNH,KX=param.KX,KA=param.KA,KH=param.KH;
        double muh=param.muh,mua=param.mua,YH=param.YH,YA=param.YA,etag=param.etag,etah=param.etah,fp=param.fp;
        double bh=param.bh,ba=param.ba,ixb=param.ixb,ixp=param.ixp,SO_max=param.SO_max;

        double SI_in=param.SI_in,SS_in=param.SS_in,XI_in=param.XI_in,XS_in=param.XS_in,XBH_in=param.XBH_in;
	double XBA_in=param.XBA_in,XP_in=param.XP_in,SO_in=param.SO_in,SNO_in=param.SNO_in,SNH_in=param.SNH_in;
	double SND_in=param.SND_in,XND_in=param.XND_in;

	double b1=(1+R)/(R+w);
	J(0,0) = -0.1e1 / tau;
	J(0,1) = 0;
	J(0,2) = 0;
	J(0,3) = 0;
	J(0,4) = 0;
	J(0,5) = 0;
	J(0,6) = 0;
	J(0,7) = 0;
	J(0,8) = 0;
	J(0,9) = 0;
	J(0,10) = 0;
	J(0,11) = 0;
	J(1,0) = 0;
	J(1,1) = -0.1e1 / tau + (-muh / YH / (KS + SS) * (KOH / (KOH + SO) * SNO / (KNO + SNO) * etag + SO / (KOH + SO)) + muh / YH * SS * pow(KS + SS, -0.2e1) * (KOH / (KOH + SO) * SNO / (KNO + SNO) * etag + SO / (KOH + SO))) * XBH;
	J(1,2) = 0;
	J(1,3) = (KH / (KX * XBH + XS) * (KOH / (KOH + SO) * SNO / (KNO + SNO) * etah + SO / (KOH + SO)) - KH * XS * pow(KX * XBH + XS, -0.2e1) * (KOH / (KOH + SO) * SNO / (KNO + SNO) * etah + SO / (KOH + SO))) * XBH;
	J(1,4) = -KH * XS * pow(KX * XBH + XS, -0.2e1) * (KOH / (KOH + SO) * SNO / (KNO + SNO) * etah + SO / (KOH + SO)) * KX * XBH - muh / YH * SS / (KS + SS) * (KOH / (KOH + SO) * SNO / (KNO + SNO) * etag + SO / (KOH + SO)) + KH * XS / (KX * XBH + XS) * (KOH / (KOH + SO) * SNO / (KNO + SNO) * etah + SO / (KOH + SO));
	J(1,5) = 0;
	J(1,6) = 0;
	J(1,7) = (-muh / YH * SS / (KS + SS) * (-KOH * pow(KOH + SO, -0.2e1) * SNO / (KNO + SNO) * etag + 0.1e1 / (KOH + SO) - SO * pow(KOH + SO, -0.2e1)) + KH * XS / (KX * XBH + XS) * (-KOH * pow(KOH + SO, -0.2e1) * SNO / (KNO + SNO) * etah + 0.1e1 / (KOH + SO) - SO * pow(KOH + SO, -0.2e1))) * XBH;
	J(1,8) = (-muh / YH * SS / (KS + SS) * (KOH / (KOH + SO) / (KNO + SNO) * etag - KOH / (KOH + SO) * SNO * pow(KNO + SNO, -0.2e1) * etag) + KH * XS / (KX * XBH + XS) * (KOH / (KOH + SO) / (KNO + SNO) * etah - KOH / (KOH + SO) * SNO * pow(KNO + SNO, -0.2e1) * etah)) * XBH;
	J(1,9) = 0;
	J(1,10) = 0;
	J(1,11) = 0;
	J(2,0) = 0;
	J(2,1) = 0;
	J(2,2) = -0.1e1 / tau + R / tau * (double) (b1 - 1);
	J(2,3) = 0;
	J(2,4) = 0;
	J(2,5) = 0;
	J(2,6) = 0;
	J(2,7) = 0;
	J(2,8) = 0;
	J(2,9) = 0;
	J(2,10) = 0;
	J(2,11) = 0;
	J(3,0) = 0;
	J(3,1) = 0;
	J(3,2) = 0;
	J(3,3) = -0.1e1 / tau + R / tau * (double) (b1 - 1) - KH / (KX * XBH + XS) * (KOH / (KOH + SO) * SNO / (KNO + SNO) * etah + SO / (KOH + SO)) * XBH + KH * XS * pow(KX * XBH + XS, -0.2e1) * (KOH / (KOH + SO) * SNO / (KNO + SNO) * etah + SO / (KOH + SO)) * XBH;
	J(3,4) = (double) ((1 - fp) * bh) + KH * XS * pow(KX * XBH + XS, -0.2e1) * (KOH / (KOH + SO) * SNO / (KNO + SNO) * etah + SO / (KOH + SO)) * KX * XBH - KH * XS / (KX * XBH + XS) * (KOH / (KOH + SO) * SNO / (KNO + SNO) * etah + SO / (KOH + SO));
	J(3,5) = (1 - fp) * ba;
	J(3,6) = 0;
	J(3,7) = -KH * XS / (KX * XBH + XS) * (-KOH * pow(KOH + SO, -0.2e1) * SNO / (KNO + SNO) * etah + 0.1e1 / (KOH + SO) - SO * pow(KOH + SO, -0.2e1)) * XBH;
	J(3,8) = -KH * XS / (KX * XBH + XS) * (KOH / (KOH + SO) / (KNO + SNO) * etah - KOH / (KOH + SO) * SNO * pow(KNO + SNO, -0.2e1) * etah) * XBH;
	J(3,9) = 0;
	J(3,10) = 0;
	J(3,11) = 0;
	J(4,0) = 0;
	J(4,1) = (muh / (KS + SS) * (KOH / (KOH + SO) * SNO / (KNO + SNO) * etag + SO / (KOH + SO)) - muh * SS * pow(KS + SS, -0.2e1) * (KOH / (KOH + SO) * SNO / (KNO + SNO) * etag + SO / (KOH + SO))) * XBH;
	J(4,2) = 0;
	J(4,3) = 0;
	J(4,4) = -0.1e1 / tau + R / tau * (double) (b1 - 1) + muh * SS / (KS + SS) * (KOH / (KOH + SO) * SNO / (KNO + SNO) * etag + SO / (KOH + SO)) - (double) bh;
	J(4,5) = 0;
	J(4,6) = 0;
	J(4,7) = muh * SS / (KS + SS) * (-KOH * pow(KOH + SO, -0.2e1) * SNO / (KNO + SNO) * etag + 0.1e1 / (KOH + SO) - SO * pow(KOH + SO, -0.2e1)) * XBH;
	J(4,8) = muh * SS / (KS + SS) * (KOH / (KOH + SO) / (KNO + SNO) * etag - KOH / (KOH + SO) * SNO * pow(KNO + SNO, -0.2e1) * etag) * XBH;
	J(4,9) = 0;
	J(4,10) = 0;
	J(4,11) = 0;
	J(5,0) = 0;
	J(5,1) = 0;
	J(5,2) = 0;
	J(5,3) = 0;
	J(5,4) = 0;
	J(5,5) = -0.1e1 / tau + R / tau * (double) (b1 - 1) + SNH / (KNH + SNH) * SO / (KOA + SO) * mua - (double) ba;
	J(5,6) = 0;
	J(5,7) = (SNH / (KNH + SNH) / (KOA + SO) * mua - SNH / (KNH + SNH) * SO * pow(KOA + SO, -0.2e1) * mua) * XBA;
	J(5,8) = 0;
	J(5,9) = (0.1e1 / (KNH + SNH) * SO / (KOA + SO) * mua - SNH * pow(KNH + SNH, -0.2e1) * SO / (KOA + SO) * mua) * XBA;
	J(5,10) = 0;
	J(5,11) = 0;
	J(6,0) = 0;
	J(6,1) = 0;
	J(6,2) = 0;
	J(6,3) = 0;
	J(6,4) = fp * bh;
	J(6,5) = fp * ba;
	J(6,6) = -0.1e1 / tau + R / tau * (double) (b1 - 1);
	J(6,7) = 0;
	J(6,8) = 0;
	J(6,9) = 0;
	J(6,10) = 0;
	J(6,11) = 0;
	J(7,0) = 0;
	J(7,1) = -muh * (0.1e1 - YH) / YH / (KS + SS) * SO / (KOH + SO) * XBH + muh * (0.1e1 - YH) / YH * SS * pow(KS + SS, -0.2e1) * SO / (KOH + SO) * XBH;
	J(7,2) = 0;
	J(7,3) = 0;
	J(7,4) = -muh * (0.1e1 - YH) / YH * SS / (KS + SS) * SO / (KOH + SO);
	J(7,5) = -mua * (0.457e1 - YA) / YA * SNH / (KNH + SNH) * SO / (KOA + SO);
	J(7,6) = 0;
	J(7,7) = -0.1e1 / tau - KLA - muh * (0.1e1 - YH) / YH * SS / (KS + SS) / (KOH + SO) * XBH + muh * (0.1e1 - YH) / YH * SS / (KS + SS) * SO * pow(KOH + SO, -0.2e1) * XBH - mua * (0.457e1 - YA) / YA * SNH / (KNH + SNH) / (KOA + SO) * XBA + mua * (0.457e1 - YA) / YA * SNH / (KNH + SNH) * SO * pow(KOA + SO, -0.2e1) * XBA;
	J(7,8) = 0;
	J(7,9) = -mua * (0.457e1 - YA) / YA / (KNH + SNH) * SO / (KOA + SO) * XBA + mua * (0.457e1 - YA) / YA * SNH * pow(KNH + SNH, -0.2e1) * SO / (KOA + SO) * XBA;
	J(7,10) = 0;
	J(7,11) = 0;
	J(8,0) = 0;
	J(8,1) = -0.3496503496e0 * muh * etag * (0.1e1 - YH) / YH / (KS + SS) * KOH / (KOH + SO) * SNO / (KNO + SNO) * XBH + 0.3496503496e0 * muh * etag * (0.1e1 - YH) / YH * SS * pow(KS + SS, -0.2e1) * KOH / (KOH + SO) * SNO / (KNO + SNO) * XBH;
	J(8,2) = 0;
	J(8,3) = 0;
	J(8,4) = -0.3496503496e0 * muh * etag * (0.1e1 - YH) / YH * SS / (KS + SS) * KOH / (KOH + SO) * SNO / (KNO + SNO);
	J(8,5) = mua / YA * SNH / (KNH + SNH) * SO / (KOA + SO);
	J(8,6) = 0;
	J(8,7) = 0.3496503496e0 * muh * etag * (0.1e1 - YH) / YH * SS / (KS + SS) * KOH * pow(KOH + SO, -0.2e1) * SNO / (KNO + SNO) * XBH + mua / YA * SNH / (KNH + SNH) / (KOA + SO) * XBA - mua / YA * SNH / (KNH + SNH) * SO * pow(KOA + SO, -0.2e1) * XBA;
	J(8,8) = -0.1e1 / tau - 0.3496503496e0 * muh * etag * (0.1e1 - YH) / YH * SS / (KS + SS) * KOH / (KOH + SO) / (KNO + SNO) * XBH + 0.3496503496e0 * muh * etag * (0.1e1 - YH) / YH * SS / (KS + SS) * KOH / (KOH + SO) * SNO * pow(KNO + SNO, -0.2e1) * XBH;
	J(8,9) = mua / YA / (KNH + SNH) * SO / (KOA + SO) * XBA - mua / YA * SNH * pow(KNH + SNH, -0.2e1) * SO / (KOA + SO) * XBA;
	J(8,10) = 0;
	J(8,11) = 0;
	J(9,0) = 0;
	J(9,1) = (-ixb * muh / (KS + SS) * (KOH / (KOH + SO) * SNO / (KNO + SNO) * etag + SO / (KOH + SO)) + ixb * muh * SS * pow(KS + SS, -0.2e1) * (KOH / (KOH + SO) * SNO / (KNO + SNO) * etag + SO / (KOH + SO))) * XBH;
	J(9,2) = 0;
	J(9,3) = 0;
	J(9,4) = -ixb * muh * SS / (KS + SS) * (KOH / (KOH + SO) * SNO / (KNO + SNO) * etag + SO / (KOH + SO)) + KA * SND;
	J(9,5) = -mua * (ixb + 0.1e1 / YA) * SNH / (KNH + SNH) * SO / (KOA + SO);
	J(9,6) = 0;
	J(9,7) = -ixb * muh * SS / (KS + SS) * (-KOH * pow(KOH + SO, -0.2e1) * SNO / (KNO + SNO) * etag + 0.1e1 / (KOH + SO) - SO * pow(KOH + SO, -0.2e1)) * XBH - mua * (ixb + 0.1e1 / YA) * SNH / (KNH + SNH) / (KOA + SO) * XBA + mua * (ixb + 0.1e1 / YA) * SNH / (KNH + SNH) * SO * pow(KOA + SO, -0.2e1) * XBA;
	J(9,8) = -ixb * muh * SS / (KS + SS) * (KOH / (KOH + SO) / (KNO + SNO) * etag - KOH / (KOH + SO) * SNO * pow(KNO + SNO, -0.2e1) * etag) * XBH;
	J(9,9) = -0.1e1 / tau - mua * (ixb + 0.1e1 / YA) / (KNH + SNH) * SO / (KOA + SO) * XBA + mua * (ixb + 0.1e1 / YA) * SNH * pow(KNH + SNH, -0.2e1) * SO / (KOA + SO) * XBA;
	J(9,10) = KA * XBH;
	J(9,11) = 0;
	J(10,0) = 0;
	J(10,1) = 0;
	J(10,2) = 0;
	J(10,3) = -KH * pow(KX * XBH + XS, -0.2e1) * XND * (KOH / (KOH + SO) * SNO / (KNO + SNO) * etah + SO / (KOH + SO)) * XBH;
	J(10,4) = -KH * pow(KX * XBH + XS, -0.2e1) * XND * (KOH / (KOH + SO) * SNO / (KNO + SNO) * etah + SO / (KOH + SO)) * KX * XBH - KA * SND + KH / (KX * XBH + XS) * XND * (KOH / (KOH + SO) * SNO / (KNO + SNO) * etah + SO / (KOH + SO));
	J(10,5) = 0;
	J(10,6) = 0;
	J(10,7) = KH / (KX * XBH + XS) * XND * (-KOH * pow(KOH + SO, -0.2e1) * SNO / (KNO + SNO) * etah + 0.1e1 / (KOH + SO) - SO * pow(KOH + SO, -0.2e1)) * XBH;
	J(10,8) = KH / (KX * XBH + XS) * XND * (KOH / (KOH + SO) / (KNO + SNO) * etah - KOH / (KOH + SO) * SNO * pow(KNO + SNO, -0.2e1) * etah) * XBH;
	J(10,9) = 0;
	J(10,10) = -0.1e1 / tau - KA * XBH;
	J(10,11) = KH / (KX * XBH + XS) * (KOH / (KOH + SO) * SNO / (KNO + SNO) * etah + SO / (KOH + SO)) * XBH;
	J(11,0) = 0;
	J(11,1) = 0;
	J(11,2) = 0;
	J(11,3) = KH * pow(KX * XBH + XS, -0.2e1) * XND * (KOH / (KOH + SO) * SNO / (KNO + SNO) * etah + SO / (KOH + SO)) * XBH;
	J(11,4) = (-(double) (fp * ixp) + ixb) * (double) bh + KH * pow(KX * XBH + XS, -0.2e1) * XND * (KOH / (KOH + SO) * SNO / (KNO + SNO) * etah + SO / (KOH + SO)) * KX * XBH - KH / (KX * XBH + XS) * XND * (KOH / (KOH + SO) * SNO / (KNO + SNO) * etah + SO / (KOH + SO));
	J(11,5) = (-(double) (fp * ixp) + ixb) * (double) ba;
	J(11,6) = 0;
	J(11,7) = -KH / (KX * XBH + XS) * XND * (-KOH * pow(KOH + SO, -0.2e1) * SNO / (KNO + SNO) * etah + 0.1e1 / (KOH + SO) - SO * pow(KOH + SO, -0.2e1)) * XBH;
	J(11,8) = -KH / (KX * XBH + XS) * XND * (KOH / (KOH + SO) / (KNO + SNO) * etah - KOH / (KOH + SO) * SNO * pow(KNO + SNO, -0.2e1) * etah) * XBH;
	J(11,9) = 0;
	J(11,10) = 0;
	J(11,11) = -0.1e1 / tau + R / tau * (double) (b1 - 1) - KH / (KX * XBH + XS) * (KOH / (KOH + SO) * SNO / (KNO + SNO) * etah + SO / (KOH + SO)) * XBH;

	return J;
}
